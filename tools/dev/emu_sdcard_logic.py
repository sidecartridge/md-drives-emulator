#!/usr/bin/env python3
"""Write the logic half of the firmware's rp/src/sdcard.c to a file of its own.

emumd stands in for sdcard.c (the SD card's hardware) and mdfw leaves any file
named sdcard.c out of a template build, but the stand-in lacks the firmware's
directory listing and path and attribute helpers. This copies them, unchanged:
the static helpers they use (from sanitizeDOSName up to
sdcard_mountFilesystem) and everything from sdcard_loadDirectory to the end.
It stops if a marker is not found, so a new firmware is noticed.

Usage:  sdcard_logic.py <firmware copy>/rp/src/sdcard.c <out.c>
"""
import sys
from pathlib import Path

HELPERS = "static void sanitizeDOSName("
HARDWARE = "FRESULT sdcard_mountFilesystem("
LOGIC = "FRESULT __not_in_flash_func(sdcard_loadDirectory)("


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    text = src.read_text()
    for marker in (HELPERS, HARDWARE, LOGIC):
        if text.count(marker) != 1:
            sys.exit(f"sdcard_logic.py: {marker!r} not found once in {src}")
    helpers = text[text.index(HELPERS):text.index(HARDWARE)]
    logic = text[text.index(LOGIC):]
    out.write_text(
        "/* Generated by tools/dev/emu_sdcard_logic.py from the firmware's\n"
        " * rp/src/sdcard.c: its logic half, unchanged. Do not edit. */\n"
        '#include "sdcard.h"\n\n' + helpers + logic)


if __name__ == "__main__":
    main()
